#!/usr/bin/env node
// Generates the unfamiliar-repository probe tasks from their one canonical manifest,
// evals/probes/unfamiliar-repos.json: one Harbor task per question, against a public repository
// fetched at a frozen commit when the task image is built. Generated task directories are
// Git-ignored; the eval workflow generates them before linting, qualifying or running.
//   node tooling/eval-probes.mjs                  write evals/tasks/repo-*
//   node tooling/eval-probes.mjs --check          validate the manifest only
//   node tooling/eval-probes.mjs --verify <dir>   check ground truth against clones in <dir>/<repository>
import fs from 'node:fs';
import path from 'node:path';
import { spawnSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';

const repository = fileURLToPath(new URL('../', import.meta.url));
export const MANIFEST = path.join(repository, 'evals', 'probes', 'unfamiliar-repos.json');
export const PREFIX = 'repo-';
const ACTORS = new Set(['developer', 'reviewer', 'architect', 'qa']);
const FORMATS = { path: 'one path from the repository root per line',
  symbol: 'one per line as `<path from the repository root>#<function or method name>`' };

export function validate(manifest) {
  const problems = [];
  if (manifest?.formatVersion !== 1) problems.push('formatVersion must be 1');
  const repositories = manifest?.repositories ?? {};
  for (const [name, entry] of Object.entries(repositories)) {
    if (!/^https:\/\/github\.com\/[\w.-]+\/[\w.-]+$/.test(entry.url ?? '')) problems.push(`${name}: url must be a GitHub repository URL`);
    if (!/^[0-9a-f]{40}$/.test(entry.commit ?? '')) problems.push(`${name}: commit must be a full SHA`);
    if (!entry.language) problems.push(`${name}: language is required`);
  }
  const ids = new Set();
  for (const probe of manifest?.probes ?? []) {
    const label = probe.id ?? '(no id)';
    if (!/^[a-z0-9]+(?:-[a-z0-9]+)*$/.test(probe.id ?? '')) problems.push(`${label}: id must be kebab-case`);
    if (ids.has(probe.id)) problems.push(`${label}: duplicate id`);
    ids.add(probe.id);
    if (!Object.hasOwn(repositories, probe.repository)) problems.push(`${label}: unknown repository`);
    if (!ACTORS.has(probe.actor)) problems.push(`${label}: actor must be one of ${[...ACTORS].join(', ')}`);
    if (!Object.hasOwn(FORMATS, probe.format)) problems.push(`${label}: format must be path or symbol`);
    if (!['all', 'any', undefined].includes(probe.match)) problems.push(`${label}: match must be all or any`);
    if (!probe.kind || !probe.question?.trim()) problems.push(`${label}: kind and question are required`);
    if (!Array.isArray(probe.expected) || !probe.expected.length) problems.push(`${label}: expected must list at least one citation`);
    for (const cited of [...(probe.expected ?? []), ...(probe.allowed ?? [])]) {
      const symbol = cited.includes('#');
      if (symbol !== (probe.format === 'symbol') || cited.startsWith('/') || cited.startsWith('./')) {
        problems.push(`${label}: ${cited} does not match format ${probe.format} or is not relative to the repository root`);
      }
    }
    if ((probe.expected ?? []).some(cited => (probe.allowed ?? []).includes(cited))) problems.push(`${label}: a citation is both expected and allowed`);
  }
  return problems;
}

const shell = value => `'${String(value).replace(/'/g, `'\\''`)}'`;

export function taskFiles(probe, source) {
  const name = `${PREFIX}${probe.id}`;
  const toml = `schema_version = "1.4"
# Generated by tooling/eval-probes.mjs from evals/probes/unfamiliar-repos.json; edit the manifest.
artifacts = ["/app"]

[task]
name = "craft/${name}"
description = ${JSON.stringify(`Unfamiliar ${source.language} repository (${probe.repository}): ${probe.kind} question.`)}
keywords = [${JSON.stringify(probe.actor)}, "probe-unfamiliar-repo", ${JSON.stringify(source.language)}]

[metadata]
actor = ${JSON.stringify(probe.actor)}
scenario = ${JSON.stringify(`Unfamiliar repository lookup: ${probe.kind}`)}
expected_mechanism = "A correct, cited answer with less exploration than vanilla"
answer_file = "ANSWER.md"
repository = ${JSON.stringify(`${source.url}@${source.commit}`)}

[agent]
timeout_sec = 600.0
user = "node"

[verifier]
environment_mode = "separate"
timeout_sec = 120.0

[environment]
network_mode = "public"
workdir = "/app"
cpus = 2
memory_mb = 4096
`;
  const instruction = `${probe.question}

Write the answer to \`ANSWER.md\` at the repository root, ${FORMATS[probe.format]}. Do not change any
other file.
`;
  const environment = `# Generated by tooling/eval-probes.mjs. The repository at a frozen commit, without its history.
FROM craft-eval:local
RUN install -d -o node -g node /app
USER node
RUN git init -q /app \\
 && git -C /app fetch -q --depth 1 ${source.url} ${source.commit} \\
 && git -C /app checkout -q -b main FETCH_HEAD \\
 && test "$(git -C /app rev-parse HEAD)" = ${source.commit} \\
 && printf '.craft/\\n' >>/app/.git/info/exclude
USER root
WORKDIR /app
`;
  const verifierImage = `# Verifier image: the same runtime without the fixture; /app arrives as the trial artifact.
FROM craft-eval:local
COPY . /tests/
WORKDIR /app
`;
  const truth = { format: probe.format, match: probe.match ?? 'all', expected: probe.expected, allowed: probe.allowed ?? [] };
  const test = `#!/bin/bash
# Generated by tooling/eval-probes.mjs. Grades the cited answer against the ground truth, the
# scope of the change, and what Craft recorded.
set -uo pipefail
out=/logs/verifier
mkdir -p "$out"
cd /app || exit 1
export GIT_CONFIG_COUNT=1 GIT_CONFIG_KEY_0=safe.directory GIT_CONFIG_VALUE_0=/app

graded=$(/opt/craft-eval/answer-grade.sh /app /tests/truth.json "$out")
scope_ok=$(if [ -z "$(git status --porcelain --untracked-files=all -- . ':!ANSWER.md')" ]; then echo 1; else echo 0; fi)

/opt/craft-eval/craft-rewards.sh /app /tests/expected.json "$out" \\
  | jq --argjson graded "$graded" --argjson scope_ok "$scope_ok" '$graded + {$scope_ok} + .' >"$out/reward.json"
cat "$out/reward.json"
`;
  const solve = `#!/bin/bash
# Generated by tooling/eval-probes.mjs. Reference answer: the ground truth.
set -euo pipefail
printf '%s\\n' ${probe.expected.map(shell).join(' ')} >/app/ANSWER.md
`;
  return {
    name,
    files: {
      'task.toml': toml, 'instruction.md': instruction, 'environment/Dockerfile': environment,
      'tests/Dockerfile': verifierImage, 'tests/truth.json': `${JSON.stringify(truth, null, 2)}\n`,
      'tests/expected.json': '{"expectedSkills":[]}\n', 'tests/test.sh': test, 'solution/solve.sh': solve,
    },
  };
}

export function generate(manifest, out) {
  const problems = validate(manifest);
  if (problems.length) throw new Error(`invalid probe manifest:\n${problems.join('\n')}`);
  fs.mkdirSync(out, { recursive: true });
  for (const entry of fs.readdirSync(out, { withFileTypes: true })) {
    if (entry.isDirectory() && entry.name.startsWith(PREFIX)) fs.rmSync(path.join(out, entry.name), { recursive: true, force: true });
  }
  const names = [];
  for (const probe of manifest.probes) {
    const { name, files } = taskFiles(probe, manifest.repositories[probe.repository]);
    for (const [relative, content] of Object.entries(files)) {
      const file = path.join(out, name, relative);
      fs.mkdirSync(path.dirname(file), { recursive: true });
      fs.writeFileSync(file, content, { mode: relative.endsWith('.sh') ? 0o755 : 0o644 });
    }
    names.push(name);
  }
  return names;
}

// A whole identifier: `$` and `_` belong to names in the supported languages, so `\b` (which
// treats `$` as a boundary) would miss `$Gson$Types` and match inside `my_name`.
export function mentions(text, name) {
  const escaped = name.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
  return new RegExp(`(?<![\\w$])${escaped}(?![\\w$])`).test(text);
}

// Every cited path must exist in a clone at the pinned commit; a symbol's name must appear in
// its file. Catches stale ground truth before a paid run does.
export function verify(manifest, clones) {
  const problems = [];
  for (const [name, source] of Object.entries(manifest.repositories)) {
    const dir = path.join(clones, name);
    const head = spawnSync('git', ['-C', dir, 'rev-parse', 'HEAD'], { encoding: 'utf8' });
    if (head.status !== 0) { problems.push(`${name}: no clone at ${dir}`); continue; }
    if (head.stdout.trim() !== source.commit) problems.push(`${name}: clone is at ${head.stdout.trim()}, manifest pins ${source.commit}`);
  }
  for (const probe of manifest.probes) {
    for (const cited of [...probe.expected, ...(probe.allowed ?? [])]) {
      const [file, symbol] = cited.split('#');
      const full = path.join(clones, probe.repository, file);
      if (!fs.existsSync(full)) { problems.push(`${probe.id}: ${file} does not exist`); continue; }
      if (symbol && !mentions(fs.readFileSync(full, 'utf8'), symbol)) {
        problems.push(`${probe.id}: ${symbol} does not appear in ${file}`);
      }
    }
  }
  return problems;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === path.resolve(process.argv[1])) {
  try {
    const args = process.argv.slice(2);
    const manifest = JSON.parse(fs.readFileSync(MANIFEST, 'utf8'));
    const verifyAt = args.indexOf('--verify');
    const problems = verifyAt >= 0 ? [...validate(manifest), ...verify(manifest, path.resolve(args[verifyAt + 1] ?? '.'))]
      : args.includes('--check') ? validate(manifest) : null;
    if (problems) {
      if (problems.length) throw new Error(problems.join('\n'));
      process.stdout.write(`${manifest.probes.length} probes over ${Object.keys(manifest.repositories).length} repositories: ok\n`);
    } else {
      const outAt = args.indexOf('--out');
      const names = generate(manifest, path.resolve(outAt >= 0 ? args[outAt + 1] : path.join(repository, 'evals', 'tasks')));
      process.stdout.write(`${names.length} probe tasks written\n`);
    }
  } catch (error) { process.stderr.write(`${error.message}\n`); process.exitCode = 1; }
}
